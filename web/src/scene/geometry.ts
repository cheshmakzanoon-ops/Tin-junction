import { RAIL_CENTER_SPACING, sampleOval } from "../model/index";
import type { LayoutDocument } from "../model/index";

export type Track = LayoutDocument["track"];
export const RAIL_TOP = 0.0072;
export { RAIL_HEAD_WIDTH } from "../model/index";
export const RAIL_OFFSET = RAIL_CENTER_SPACING / 2;
export const BOARD_WIDTH = 0.8;
export const BOARD_DEPTH = 0.5;

/** Presentation-only RNG. Authoritative layout variation is generated by the model. */
export function visualRandom(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    return state / 4294967296;
  };
}

export function loopLength(track: Track): number { return 2 * track.straightLength + 2 * Math.PI * track.radius; }

/** A closed, consistently wound profile sweep using the same analytic curve as the train. */
export function sweepProfile(track: Track, profile: ReadonlyArray<readonly [number, number]>, segments = 384): THREE.BufferGeometry {
  if (profile.length < 3 || !Number.isInteger(segments) || segments < 8 || segments > 2048) throw new Error("Invalid rail profile sweep");
  if (profile.some(point => point.some(value => !Number.isFinite(value)))) throw new Error("Non-finite rail profile");
  const positions: number[] = [];
  const uv: number[] = [];
  const indices: number[] = [];
  const length = loopLength(track);
  for (let index = 0; index <= segments; index += 1) {
    const point = sampleOval(track, length * index / segments);
    for (let edge = 0; edge < profile.length; edge += 1) {
      const [offset, height] = profile[edge]!;
      positions.push(point.position.x + point.tangent.z * offset, height, point.position.z - point.tangent.x * offset);
      uv.push(index / segments * length * 14, edge / profile.length);
    }
  }
  const stride = profile.length;
  for (let index = 0; index < segments; index += 1) {
    for (let edge = 0; edge < stride; edge += 1) {
      const a = index * stride + edge;
      const b = (index + 1) * stride + edge;
      const c = index * stride + (edge + 1) % stride;
      const d = (index + 1) * stride + (edge + 1) % stride;
      indices.push(a, c, b, b, c, d);
    }
  }
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute("position", new THREE.Float32BufferAttribute(positions, 3));
  geometry.setAttribute("uv", new THREE.Float32BufferAttribute(uv, 2));
  geometry.setIndex(indices);
  geometry.computeVertexNormals();
  geometry.computeBoundingSphere();
  return geometry;
}

export function rectangularRail(track: Track, offset: number, width: number, bottom: number, top: number): THREE.BufferGeometry {
  return sweepProfile(track, [[offset - width / 2, bottom], [offset + width / 2, bottom], [offset + width / 2, top], [offset - width / 2, top]]);
}

export function distanceFromTrack(x: number, z: number, track: Track): number {
  const beyond = Math.max(0, Math.abs(x) - track.straightLength / 2);
  return Math.abs(Math.hypot(beyond, z) - track.radius);
}

/** Tiny handmade landforms; all track beds and the station stay planar. */
export function terrainHeight(x: number, z: number, track: Track): number {
  const clearance = THREE.MathUtils.smoothstep(distanceFromTrack(x, z, track), 0.025, 0.055);
  const station = Math.abs(x) < 0.13 && z < -0.045 && z > -0.14 ? 0 : 1;
  const pond = x > 0.14 && x < 0.27 && z > 0.025 && z < 0.105 ? 0 : 1;
  const hill = 0.017 * Math.exp(-(((x + 0.21) / 0.066) ** 2) - ((z - 0.015) / 0.065) ** 2)
    + 0.022 * Math.exp(-(((x - 0.22) / 0.075) ** 2) - ((z + 0.04) / 0.053) ** 2);
  const ripple = 0.0006 * (1 + Math.sin(x * 90) * Math.cos(z * 73));
  return 0.0004 + (hill + ripple) * clearance * station * pond;
}

export function makeTerrain(track: Track): THREE.BufferGeometry {
  const geometry = new THREE.PlaneGeometry(BOARD_WIDTH, BOARD_DEPTH, 96, 64);
  geometry.rotateX(-Math.PI / 2);
  const positions = geometry.getAttribute("position");
  const colors: number[] = [];
  for (let index = 0; index < positions.count; index += 1) {
    const x = positions.getX(index), z = positions.getZ(index);
    positions.setY(index, terrainHeight(x, z, track));
    const fleck = 0.91 + 0.09 * Math.sin(x * 55 + z * 31) * Math.cos(x * 22 - z * 42);
    colors.push(fleck, fleck, fleck * 0.98);
  }
  geometry.setAttribute("color", new THREE.Float32BufferAttribute(colors, 3));
  geometry.computeVertexNormals();
  return geometry;
}

export function box(parent: THREE.Object3D, size: [number, number, number], position: [number, number, number], material: THREE.Material, bevel = 0): THREE.Mesh {
  const geometry = bevel > 0 ? new RoundedBoxGeometry(...size, 2, Math.min(bevel, Math.min(...size) / 3)) : new THREE.BoxGeometry(...size);
  const mesh = new THREE.Mesh(geometry, material);
  mesh.position.set(...position);
  mesh.castShadow = true;
  mesh.receiveShadow = true;
  parent.add(mesh);
  return mesh;
}

export function cylinder(parent: THREE.Object3D, top: number, bottom: number, height: number, position: [number, number, number], material: THREE.Material, segments = 16): THREE.Mesh {
  const mesh = new THREE.Mesh(new THREE.CylinderGeometry(top, bottom, height, segments), material);
  mesh.position.set(...position);
  mesh.castShadow = true;
  mesh.receiveShadow = true;
  parent.add(mesh);
  return mesh;
}

/** Collapse original procedural components by material, retaining one reusable geometry per material. */
export function compactGroup(group: THREE.Group): THREE.Group {
  group.updateMatrixWorld(true);
  const inverse = group.matrixWorld.clone().invert();
  const geometries = new Map<THREE.Material, THREE.BufferGeometry[]>();
  const originals = new Set<THREE.BufferGeometry>();
  group.traverse(object => {
    if (!(object instanceof THREE.Mesh) || Array.isArray(object.material)) return;
    const geometry = object.geometry.clone().applyMatrix4(new THREE.Matrix4().multiplyMatrices(inverse, object.matrixWorld));
    const compatible = geometry.index ? geometry.toNonIndexed() : geometry;
    if (compatible !== geometry) geometry.dispose();
    // Primitive geometries expose the same position, normal and UV attributes.
    const list = geometries.get(object.material) ?? [];
    list.push(compatible);
    geometries.set(object.material, list);
    originals.add(object.geometry);
  });
  group.clear();
  for (const [material, parts] of geometries) {
    const geometry = mergeGeometries(parts);
    if (!geometry) throw new Error("Could not combine procedural scene parts");
    parts.forEach(part => part.dispose());
    const mesh = new THREE.Mesh(geometry, material);
    mesh.castShadow = true;
    mesh.receiveShadow = true;
    group.add(mesh);
  }
  originals.forEach(geometry => geometry.dispose());
  return group;
}
